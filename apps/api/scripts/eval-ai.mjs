// Accuracy report: rules only vs Gemini only vs hybrid, per email set. Needs GEMINI_API_KEY (apps/api/.env).
// Run: pnpm --filter api build && pnpm --filter api eval:ai   → prints a table and writes docs/accuracy-ai.md
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { runTriage } from "@c16/core";
import { classifyEmails, aiModel } from "../dist/services/ai.js";

if (existsSync(".env")) process.loadEnvFile(".env");
const root = new URL("../../../", import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), "utf8"));

const fixture = read("data/fixture/C16/fixture.json").records.emails;
const labels = new Map(read("data/labels/C16_labels.json").labels.map((l) => [l.email_id, l.purpose]));
const sets = {
  "Fixture E01–E12": fixture.map((e) => ({ id: e.email_id, body: e.body, purpose: labels.get(e.email_id) })),
  "Robustness (rules tuned on it)": read("packages/core/tests/fixtures/robustness.json").emails,
  "Dev set v1 (seen while tuning)": read("packages/core/tests/fixtures/heldout.json").emails,
  "Held-out v2 (never tuned on)": read("packages/core/tests/fixtures/heldout_v2.json").emails,
};

const one = (e, ai) =>
  runTriage({ case_id: "C16", records: { emails: [{ email_id: e.id, subject: "-", body: e.body, received_at: "2026-10-16T10:00:00+05:30" }], policy: { draft_only: true, auto_send: false } } }, ai ? { ai: { [e.id]: ai } } : {}).decisions[0];

const rows = [];
const misses = [];
for (const [name, emails] of Object.entries(sets)) {
  const ai = await classifyEmails(emails.map((e) => ({ email_id: e.id, subject: "-", body: e.body })));
  if (ai.status !== "ok") throw new Error(`AI ${ai.status}: ${ai.error ?? "set GEMINI_API_KEY"}`);
  let rules = 0, model = 0, hybrid = 0, review = 0;
  for (const e of emails) {
    const p = ai.predictions[e.id];
    if (one(e).purpose === e.purpose) rules++;
    if (p?.purpose === e.purpose) model++;
    const h = one(e, p);
    if (h.purpose === e.purpose) hybrid++;
    else misses.push(`| ${name} | ${e.id} | ${e.purpose} | ${h.purpose} | ${e.body.replace(/\n/g, " ").replace(/\|/g, "/")} |`);
    if (h.review.needed) review++;
  }
  const pct = (n) => `${n}/${emails.length} (${Math.round((n / emails.length) * 100)}%)`;
  rows.push(`| ${name} | ${pct(rules)} | ${pct(model)} | ${pct(hybrid)} | ${review} |`);
}

const md = `# Email-type accuracy

Generated by \`apps/api/scripts/eval-ai.mjs\` on ${new Date().toISOString().slice(0, 10)} with \`${aiModel()}\` (temperature 0). Each email is triaged on its own.
All sets are synthetic and written by the team; they are not a benchmark.

| Set | Rules only | Gemini only | Hybrid (shipped) | Flagged for review |
|---|---|---|---|---|
${rows.join("\n")}

Hybrid = rules decide when a rule matches; Gemini decides when none does; disagreements are flagged for a person, and Gemini overrules a rule only at ≥ 80% confidence. Injections caught by the rules are never released by the model. Facts (dates, owners, ids) always come from the rules.

## Hybrid misses
| Set | Email | Expected | Got | Text |
|---|---|---|---|---|
${misses.join("\n") || "| – | – | – | – | none |"}
`;
writeFileSync(new URL("docs/accuracy-ai.md", root), md);
console.log(md);
